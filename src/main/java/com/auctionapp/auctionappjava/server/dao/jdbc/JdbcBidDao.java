package com.auctionapp.auctionappjava.server.dao.jdbc;

import com.auctionapp.auctionappjava.common.model.BidTransaction;
import com.auctionapp.auctionappjava.server.dao.BidDao;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

public class JdbcBidDao extends JdbcDaoSupport implements BidDao {
    @Override
    public BidTransaction save(BidTransaction bidTransaction) {
        String sql = """
                INSERT INTO bids (
                    id, auction_id, bidder_id, amount, auto_generated, note, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                
                """;
        try (Connection connection = connection(); PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, uuid(bidTransaction.getId()));
            statement.setString(2, uuid(bidTransaction.getAuctionId()));
            statement.setString(3, uuid(bidTransaction.getBidderId()));
            statement.setBigDecimal(4, bidTransaction.getAmount());
            statement.setBoolean(5, bidTransaction.isAutoGenerated());
            statement.setString(6, bidTransaction.getNote());
            statement.setTimestamp(7, timestamp(bidTransaction.getCreatedAt()));
            statement.setTimestamp(8, timestamp(bidTransaction.getUpdatedAt()));
            statement.executeUpdate();
            return bidTransaction;
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong luu duoc bid", exception);
        }
    }

    @Override
    public List<BidTransaction> findByAuctionId(UUID auctionId) {
        String sql = "SELECT * FROM bids WHERE auction_id = ? ORDER BY created_at";
        try (Connection connection = connection(); PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, uuid(auctionId));
            try (ResultSet resultSet = statement.executeQuery()) {
                List<BidTransaction> bids = new ArrayList<>();
                while (resultSet.next()) {
                    bids.add(mapBid(resultSet));
                }
                return bids;
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong doc duoc danh sach bid", exception);
        }
    }

    @Override
    public Optional<BidTransaction> findLatestBidByBidderId(UUID bidderId) {
        String sql = """
        SELECT * FROM bids 
        WHERE bidder_id = ? 
        ORDER BY created_at DESC 
        LIMIT 1
        """;

        try (Connection connection = connection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, uuid(bidderId));

            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next() ? Optional.of(mapBid(resultSet)) : Optional.empty();
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong tim duoc bid moi nhat cua bidder: " + bidderId, exception);
        }
    }


    @Override
    public Optional<BidTransaction> findHighestBidByAuctionId(UUID auctionId) {
        // Sắp xếp amount giảm dần (DESC) và lấy 1 kết quả đầu tiên
        String sql = "SELECT * FROM bids WHERE auction_id = ? ORDER BY amount DESC LIMIT 1";

        try (Connection connection = connection(); PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, uuid(auctionId));

            try (ResultSet resultSet = statement.executeQuery()) {
                // Nếu có kết quả thì map ra đối tượng Bid, nếu không thì trả về Optional.empty()
                return resultSet.next() ? Optional.of(mapBid(resultSet)) : Optional.empty();
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong tim thay bid cao nhat cua phien dau gia", exception);
        }
    }

    @Override
    public List<BidTransaction> findByBidderId(UUID bidderId) {
        String sql = "SELECT * FROM bids WHERE bidder_id = ? ORDER BY created_at DESC";

        try (Connection connection = connection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, uuid(bidderId));

            try (ResultSet resultSet = statement.executeQuery()) {
                List<BidTransaction> bidHistory = new ArrayList<>();
                while (resultSet.next()) {
                    bidHistory.add(mapBid(resultSet));
                }
                return bidHistory;
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Không thể tải lịch sử đặt giá của bidder: " + bidderId, exception);
        }
    }

    @Override
    public List<BidTransaction> findAll() {
        String sql = "SELECT * FROM bids ORDER BY created_at";

        try (Connection connection = connection(); PreparedStatement statement = connection.prepareStatement(sql)) {

            try (ResultSet resultSet = statement.executeQuery()) {
                List<BidTransaction> transactions = new ArrayList<>();
                while (resultSet.next()) {
                    transactions.add(mapBid(resultSet));
                }
                return transactions;
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong doc duoc danh sach auction", exception);
        }
    }

    @Override
    public long countByAuctionId(UUID auctionId) {
        return countBySql("SELECT COUNT(*) FROM bids WHERE auction_id = ?", uuid(auctionId));
    }

    @Override
    public long countByBidderId(UUID bidderId) {
        return countBySql("SELECT COUNT(*) FROM bids WHERE bidder_id = ?", uuid(bidderId));
    }

    @Override
    public long countBidsByBidderId(UUID bidderId) {
        String sql = "SELECT COUNT(DISTINCT auction_id) FROM bids WHERE bidder_id = ?";

        try (Connection connection = connection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            // Set giá trị id của phiên đấu giá (nhớ parse UUID sang String vì DB bạn dùng VARCHAR(36))
            statement.setString(1, uuid(bidderId));

            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return resultSet.getLong(1); // Lấy kết quả đếm được trả về
                }
                return 0L; // Trả về 0 nếu chưa có ai đặt giá
            }

        } catch (SQLException exception) {
            throw new IllegalStateException("Khong dem duoc so luong auction cho bidder_id: " + bidderId, exception);
        }
    }

    @Override
    public long countBiddersByAuctionId(UUID auctionId) {
        // Dùng DISTINCT để đảm bảo 1 người dù đặt 10 lần thì cũng chỉ đếm là 1 người
        String sql = "SELECT COUNT(DISTINCT bidder_id) FROM bids WHERE auction_id = ?";

        try (Connection connection = connection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            // Set giá trị id của phiên đấu giá (nhớ parse UUID sang String vì DB bạn dùng VARCHAR(36))
            statement.setString(1, uuid(auctionId));

            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return resultSet.getLong(1); // Lấy kết quả đếm được trả về
                }
                return 0L; // Trả về 0 nếu chưa có ai đặt giá
            }

        } catch (SQLException exception) {
            throw new IllegalStateException("Khong dem duoc so luong  bidder cho auction_id: " + auctionId, exception);
        }
    }

    @Override
    public void deleteByAuctionId(UUID auctionId) {
        String sql = "DELETE FROM bids WHERE auction_id = ?";
        try (Connection connection = connection(); PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, uuid(auctionId));
            statement.executeUpdate();
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong xoa duoc bid", exception);
        }
    }

    private long countBySql(String sql, String value) {
        try (Connection connection = connection(); PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, value);
            try (ResultSet resultSet = statement.executeQuery()) {
                resultSet.next();
                return resultSet.getLong(1);
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Khong dem duoc bid", exception);
        }
    }

    private BidTransaction mapBid(ResultSet resultSet) throws SQLException {
        return new BidTransaction(
                uuid(resultSet.getString("id")),
                localDateTime(resultSet.getTimestamp("created_at")),
                localDateTime(resultSet.getTimestamp("updated_at")),
                uuid(resultSet.getString("auction_id")),
                uuid(resultSet.getString("bidder_id")),
                resultSet.getBigDecimal("amount"),
                resultSet.getBoolean("auto_generated"),
                resultSet.getString("note"));
    }
}
